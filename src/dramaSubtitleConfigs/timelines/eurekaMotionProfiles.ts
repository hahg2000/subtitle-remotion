import type {
  SubtitleHiddenFrameWindow,
  SubtitleMoveDirection,
} from "../../subtitleEffects/types";
import type { VerticalCharacterMotion } from "./helpers";

type FlickerPattern = 0 | 1 | 2;
type MotionTuple = readonly [
  atFrame: number,
  direction: SubtitleMoveDirection,
  distance: number,
  durationInFrames: number,
  flicker: FlickerPattern,
];

const HIDDEN_WINDOWS = {
  0: [],
  1: [{ startFrame: 1, durationInFrames: 1 }],
  2: [
    { startFrame: 1, durationInFrames: 1 },
    { startFrame: 3, durationInFrames: 1 },
  ],
} satisfies Record<FlickerPattern, SubtitleHiddenFrameWindow[]>;

const defineMotionProfile = (
  columns: readonly (readonly MotionTuple[])[],
): VerticalCharacterMotion[][] =>
  columns.map((column) =>
    column.map(
      ([
        atFrame,
        moveDirection,
        moveDistance,
        animationDurationInFrames,
        flicker,
      ]) => ({
        atFrame,
        moveDirection,
        moveDistance,
        animationDurationInFrames,
        hiddenWindows: HIDDEN_WINDOWS[flicker],
      }),
    ),
  );

